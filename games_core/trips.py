# (от скольких км, восхищение) — от большего к меньшему
CHEERS = (
    (5000, "Фантастика!"),
    (1000, "Невероятно!"),
    (300, "Вот это заезд!"),
    (1, "Отличная поездка!"),
)


def road_weight(level: int) -> float:
    """Доля дороги, которую на этом уровне проезжает партия без ошибок."""
    if level >= FULL_ROAD_LEVEL:
        return 1.0
    for (l1, w1), (l2, w2) in zip(ROAD_WEIGHTS, ROAD_WEIGHTS[1:]):
        if level <= l2:
            return w1 + (w2 - w1) * (max(level, l1) - l1) / (l2 - l1)
    return 1.0


def trip_lines(km: int) -> List[str]:
    if km <= 0:
        return [t("trip_none")]
    cheer = next(text for threshold, text in CHEERS if km >= threshold)
    lines = [t("trip_km", cheer=cheer, km=km)]
    reached = [(dist, what) for dist, what in TRIPS if dist <= km]
    if reached:
        dist, what = reached[-1]
        lines.append(t("trip_reached", what=what, dist=dist))
    else:
        dist, what = TRIPS[0]
        lines.append(t("trip_almost", what=what, left=dist - km))
    return lines
